// renderSharedComponents generates shared React components and utilities.
func renderSharedComponents(usedTypes []string) ([]renderer.OutputFile, error) {
	typeSet := map[string]bool{}
	for _, t := range usedTypes {
		typeSet[t] = true
	}

	var files []renderer.OutputFile

	// DataTable component if data-table is used
	if typeSet["data-table"] {
		files = append(files, generateDataTableComponent())
	}

	// cn() utility (always generated — used by shadcn components)
	files = append(files, generateCNUtil())

	// Re-export barrel for used shadcn components
	files = append(files, generateComponentIndex(usedTypes))

	return files, nil
}

func generateDataTableComponent() renderer.OutputFile {
	content := `// data-table.tsx
// Generated by Sigil — do not edit manually
"use client";

import {
  ColumnDef,
  flexRender,
  getCoreRowModel,
  useReactTable,
} from "@tanstack/react-table";

import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";

interface DataTableProps<TData, TValue> {
  columns: ColumnDef<TData, TValue>[];
  data: TData[];
}

export function DataTable<TData, TValue>({
  columns,
  data,
}: DataTableProps<TData, TValue>) {
  const table = useReactTable({
    data,
    columns,
    getCoreRowModel: getCoreRowModel(),
  });

  return (
    <div className="rounded-md border">
      <Table>
        <TableHeader>
          {table.getHeaderGroups().map((headerGroup) => (
            <TableRow key={headerGroup.id}>
              {headerGroup.headers.map((header) => (
                <TableHead key={header.id}>
                  {header.isPlaceholder
                    ? null
                    : flexRender(
                        header.column.columnDef.header,
                        header.getContext()
                      )}
                </TableHead>
              ))}
            </TableRow>
          ))}
        </TableHeader>
        <TableBody>
          {table.getRowModel().rows?.length ? (
            table.getRowModel().rows.map((row) => (
              <TableRow key={row.id}>
                {row.getVisibleCells().map((cell) => (
                  <TableCell key={cell.id}>
                    {flexRender(cell.column.columnDef.cell, cell.getContext())}
                  </TableCell>
                ))}
              </TableRow>
            ))
          ) : (
            <TableRow>
              <TableCell colSpan={columns.length} className="h-24 text-center">
                No results.
              </TableCell>
            </TableRow>
          )}
        </TableBody>
      </Table>
    </div>
  );
}
`
	return renderer.OutputFile{
		Path:    "components/data-table.tsx",
		Content: []byte(content),
	}
}

func generateCNUtil() renderer.OutputFile {
	content := `// lib/utils.ts
// Generated by Sigil — do not edit manually
import { type ClassValue, clsx } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
`
	return renderer.OutputFile{
		Path:    "lib/utils.ts",
		Content: []byte(content),
	}
}

func generateComponentIndex(usedTypes []string) renderer.OutputFile {
	sort.Strings(usedTypes)

	var buf bytes.Buffer
	buf.WriteString("// components/index.ts\n")
	buf.WriteString("// Generated by Sigil — do not edit manually\n")
	buf.WriteString("// Re-exports for components used in this project.\n\n")

	shadcnMap := map[string]string{
		"button":     "button",
		"badge":      "badge",
		"input":      "input",
		"select":     "select",
		"separator":  "separator",
		"progress":   "progress",
		"avatar":     "avatar",
		"alert":      "alert",
		"label":      "label",
		"modal":      "dialog",
		"sheet":      "sheet",
		"tabs":       "tabs",
		"form":       "form",
		"data-table": "table",
	}

	exported := map[string]bool{}
	for _, t := range usedTypes {
		if shadcnComp, ok := shadcnMap[t]; ok && !exported[shadcnComp] {
			exported[shadcnComp] = true
			buf.WriteString(fmt.Sprintf("export * from \"@/components/ui/%s\";\n", shadcnComp))
		}
	}

	if hasType(usedTypes, "data-table") {
		buf.WriteString("export { DataTable } from \"@/components/data-table\";\n")
	}

	return renderer.OutputFile{
		Path:    "components/index.ts",
		Content: buf.Bytes(),
	}
}

func hasType(types []string, t string) bool {
	for _, tt := range types {
		if tt == t {
			return true
		}
	}
	return false
}

// renderDataSourceHooks generates TypeScript hooks for datasource API access.
func renderDataSourceHooks(ds *renderer.DataSourceManifest) ([]renderer.OutputFile, error) {
	var files []renderer.OutputFile

	// Types file
	typesFile := generateDSTypes(ds)
	files = append(files, typesFile)

	// Hook file
	hookFile := generateDSHook(ds)
	files = append(files, hookFile)

	return files, nil
}

func generateDSTypes(ds *renderer.DataSourceManifest) renderer.OutputFile {
	alias := ds.Alias
	typeName := toPascalCase(alias)
	fileName := toKebabCase(alias) + ".ts"

	var buf bytes.Buffer
	buf.WriteString(fmt.Sprintf("// types/%s\n", fileName))
	buf.WriteString("// Generated by Sigil — do not edit manually\n\n")

	// Main type
	buf.WriteString(fmt.Sprintf("export interface %s {\n", typeName))
	for _, f := range ds.Fields {
		tsType := fieldTSType(f.Type)
		optional := ""
		if !f.Required && !f.Primary {
			optional = "?"
		}
		buf.WriteString(fmt.Sprintf("  %s%s: %s;\n", f.Name, optional, tsType))
	}
	buf.WriteString("}\n\n")

	// Input type (for create/update — excludes primary, readonly, hidden)
	buf.WriteString(fmt.Sprintf("export interface %sInput {\n", typeName))
	for _, f := range ds.Fields {
		if f.Primary || f.Readonly || f.Hidden {
			continue
		}
		tsType := fieldTSType(f.Type)
		optional := ""
		if !f.Required {
			optional = "?"
		}
		buf.WriteString(fmt.Sprintf("  %s%s: %s;\n", f.Name, optional, tsType))
	}
	buf.WriteString("}\n")

	return renderer.OutputFile{
		Path:    "types/" + fileName,
		Content: buf.Bytes(),
	}
}

func generateDSHook(ds *renderer.DataSourceManifest) renderer.OutputFile {
	alias := ds.Alias
	typeName := toPascalCase(alias)
	hookName := "use" + typeName
	fileName := "use-" + toKebabCase(alias) + ".ts"

	var buf bytes.Buffer
	buf.WriteString(fmt.Sprintf("// hooks/%s\n", fileName))
	buf.WriteString("// Generated by Sigil — do not edit manually\n\n")
	buf.WriteString("import useSWR from \"swr\";\n")
	buf.WriteString(fmt.Sprintf("import type { %s, %sInput } from \"@/types/%s\";\n\n", typeName, typeName, toKebabCase(alias)))

	buf.WriteString("const fetcher = (url: string) => fetch(url).then((res) => res.json());\n\n")

	// List hook
	listEndpoint := ds.Endpoints["list"]
	if listEndpoint == "" {
		listEndpoint = "/api/" + strings.ToLower(alias) + "s"
	}
	// Extract just the path from "GET /api/..."
	listPath := extractPath(listEndpoint)

	buf.WriteString(fmt.Sprintf("export function %s() {\n", hookName))
	buf.WriteString(fmt.Sprintf("  return useSWR<%s[]>(%q, fetcher);\n", typeName, listPath))
	buf.WriteString("}\n\n")

	// Get by ID hook
	if _, ok := ds.Endpoints["read"]; ok {
		readPath := extractPath(ds.Endpoints["read"])
		// Replace {id} with template literal
		readPath = strings.Replace(readPath, "{id}", "${id}", 1)
		buf.WriteString(fmt.Sprintf("export function %sById(id: string) {\n", hookName))
		buf.WriteString(fmt.Sprintf("  return useSWR<%s>(id ? `%s` : null, fetcher);\n", typeName, readPath))
		buf.WriteString("}\n\n")
	}

	// Mutation helpers
	if ds.HasCapability("create") {
		createPath := extractPath(ds.Endpoints["create"])
		buf.WriteString(fmt.Sprintf("export async function create%s(input: %sInput): Promise<%s> {\n", typeName, typeName, typeName))
		buf.WriteString(fmt.Sprintf("  const res = await fetch(%q, {\n", createPath))
		buf.WriteString("    method: \"POST\",\n")
		buf.WriteString("    headers: { \"Content-Type\": \"application/json\" },\n")
		buf.WriteString("    body: JSON.stringify(input),\n")
		buf.WriteString("  });\n")
		buf.WriteString("  return res.json();\n")
		buf.WriteString("}\n\n")
	}

	if ds.HasCapability("update") {
		updatePath := extractPath(ds.Endpoints["update"])
		updatePath = strings.Replace(updatePath, "{id}", "${id}", 1)
		buf.WriteString(fmt.Sprintf("export async function update%s(id: string, input: Partial<%sInput>): Promise<%s> {\n", typeName, typeName, typeName))
		buf.WriteString(fmt.Sprintf("  const res = await fetch(`%s`, {\n", updatePath))
		buf.WriteString("    method: \"PUT\",\n")
		buf.WriteString("    headers: { \"Content-Type\": \"application/json\" },\n")
		buf.WriteString("    body: JSON.stringify(input),\n")
		buf.WriteString("  });\n")
		buf.WriteString("  return res.json();\n")
		buf.WriteString("}\n\n")
	}

	if ds.HasCapability("delete") {
		deletePath := extractPath(ds.Endpoints["delete"])
		deletePath = strings.Replace(deletePath, "{id}", "${id}", 1)
		buf.WriteString(fmt.Sprintf("export async function delete%s(id: string): Promise<void> {\n", typeName))
		buf.WriteString(fmt.Sprintf("  await fetch(`%s`, { method: \"DELETE\" });\n", deletePath))
		buf.WriteString("}\n")
	}

	return renderer.OutputFile{
		Path:    "hooks/" + fileName,
		Content: buf.Bytes(),
	}
}

func fieldTSType(fieldType string) string {
	switch fieldType {
	case "string", "text", "enum":
		return "string"
	case "integer", "float":
		return "number"
	case "boolean":
		return "boolean"
	case "date", "datetime":
		return "string" // ISO 8601 string in JSON
	case "json":
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func extractPath(endpoint string) string {
	// Endpoints are like "GET /api/sprints" — extract just the path
	parts := strings.Fields(endpoint)
	if len(parts) >= 2 {
		return parts[1]
	}
	return endpoint
}
