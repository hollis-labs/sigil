func renderReactActions(actions map[string]config.Action, imports *importTracker) string {
	if len(actions) == 0 {
		return ""
	}

	var attrs []string
	for _, action := range actions {
		switch action.Type {
		case "navigate":
			imports.addReact("useRouter", "next/navigation")
			if action.URL != "" {
				url := interpolateActionURL(action.URL)
				attrs = append(attrs, fmt.Sprintf(` onClick={() => router.push(%s)}`, url))
			} else if action.Page != "" {
				route := pageRoute(action.Page, imports.pageModule)
				attrs = append(attrs, fmt.Sprintf(` onClick={() => router.push(%q)}`, route))
			}
		case "http":
			method := strings.ToUpper(action.Method)
			if method == "" {
				method = "POST"
			}
			url := interpolateActionURL(action.URL)
			if action.OnSuccess != nil && action.OnSuccess.Type == "toast" {
				imports.addReact("toast", "sonner")
				imports.addShadcn("Toaster", "@/components/ui/sonner")
				msg := action.OnSuccess.Message
				if msg == "" {
					msg = "Success"
				}
				toastCall := renderToastCall(action.OnSuccess)
				// Include form resets after toast if available
				if len(imports.formResetters) > 0 {
					resetCalls := strings.Join(imports.formResetters, "; ")
					attrs = append(attrs, fmt.Sprintf(` onClick={() => fetch(%s, { method: %q }).then(() => { %s; %s; })}`, url, method, toastCall, resetCalls))
				} else {
					attrs = append(attrs, fmt.Sprintf(` onClick={() => fetch(%s, { method: %q }).then(() => %s)}`, url, method, toastCall))
				}
			} else {
				attrs = append(attrs, fmt.Sprintf(` onClick={() => fetch(%s, { method: %q })}`, url, method))
			}
		case "toast":
			imports.addReact("toast", "sonner")
			imports.addShadcn("Toaster", "@/components/ui/sonner")
			toastCall := renderToastCall(&action)
			attrs = append(attrs, fmt.Sprintf(` onClick={() => %s}`, toastCall))
		case "filter":
			// Filter emits a custom event with datasource + field + value for filtering
			ds := action.Datasource
			field := action.Field
			if ds != "" && field != "" {
				attrs = append(attrs, fmt.Sprintf(` onChange={(e) => window.dispatchEvent(new CustomEvent("filter:%s", { detail: { field: %q, value: e.target.value } }))}`, strings.ToLower(ds), field))
			}
		case "create":
			// Create navigates to a create page or opens a modal
			imports.addReact("useRouter", "next/navigation")
			if action.Page != "" {
				route := pageRoute(action.Page, imports.pageModule)
				attrs = append(attrs, fmt.Sprintf(` onClick={() => router.push(%q)}`, route+"/new"))
			} else if action.URL != "" {
				url := interpolateActionURL(action.URL)
				attrs = append(attrs, fmt.Sprintf(` onClick={() => router.push(%s)}`, url))
			}
		case "emit":
			if action.Event != "" {
				attrs = append(attrs, fmt.Sprintf(` onClick={() => window.dispatchEvent(new CustomEvent(%q))}`, action.Event))
			} else if action.Datasource != "" && action.Field != "" {
				// emit with datasource/field acts as a filter event
				attrs = append(attrs, fmt.Sprintf(` onChange={(e) => window.dispatchEvent(new CustomEvent("filter:%s", { detail: { field: %q, value: e.target.value } }))}`, strings.ToLower(action.Datasource), action.Field))
			}
		case "confirm":
			if action.Message != "" {
				attrs = append(attrs, fmt.Sprintf(` onClick={() => { if (window.confirm(%q)) { /* action */ } }}`, action.Message))
			}
		case "close":
			attrs = append(attrs, ` onClick={() => setOpen(false)}`)
		}
	}
	return strings.Join(attrs, "")
}

// importTracker collects and deduplicates imports for a TSX file.
type importTracker struct {
	// module -> set of named imports
	shadcn map[string]map[string]bool
	lucide map[string]bool
	react  map[string]map[string]bool
	local  map[string]map[string]bool
	// stateDecls collects useState declarations needed by components (e.g., date-pickers)
	stateDecls []string
	// searchDatasources tracks datasources that have a search-bar wired to them (datasource name -> state var)
	searchDatasources map[string]string
	// filterBindings tracks select filters wired to datasources (datasource name -> [{field, stateVar}])
	filterBindings map[string][]filterBinding
	// formResetters collects setter calls to reset form state (e.g., "setDeployName(\"\")")
	formResetters []string
	// pageModule is the module prefix for the current page (e.g., "forge")
	pageModule string
}

type filterBinding struct {
	field    string
	stateVar string
}

func newImportTracker() *importTracker {
	return &importTracker{
		shadcn: map[string]map[string]bool{},
		lucide: map[string]bool{},
		react:  map[string]map[string]bool{},
		local:  map[string]map[string]bool{},
	}
}

