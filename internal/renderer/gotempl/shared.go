// renderSharedComponents generates reusable .templ component files.
func renderSharedComponents(usedTypes []string) ([]renderer.OutputFile, error) {
	typeSet := map[string]bool{}
	for _, t := range usedTypes {
		typeSet[t] = true
	}

	var files []renderer.OutputFile

	// Always generate layout helpers
	files = append(files, generateLayoutHelpers())

	// Generate component files based on what's used
	generators := map[string]func() renderer.OutputFile{
		"button":     generateButtonTempl,
		"heading":    generateHeadingTempl,
		"text":       generateTextTempl,
		"badge":      generateBadgeTempl,
		"input":      generateInputTempl,
		"select":     generateSelectTempl,
		"search-bar": generateSearchBarTempl,
		"data-table": generateDataTableTempl,
		"modal":      generateModalTempl,
		"form":       generateFormTempl,
	}

	for typeName, gen := range generators {
		if typeSet[typeName] {
			files = append(files, gen())
		}
	}

	return files, nil
}

func generateLayoutHelpers() renderer.OutputFile {
	content := `// layout_helpers.templ
// Generated by Sigil — do not edit manually
package components

// Rows renders a vertical flex container.
templ Rows(class string) {
    <div class={ "flex flex-col " + class }>
        { children... }
    </div>
}

// Columns renders a horizontal flex container.
templ Columns(class string) {
    <div class={ "flex flex-row " + class }>
        { children... }
    </div>
}

// Grid renders a CSS grid container.
templ Grid(cols int, class string) {
    <div class={ fmt.Sprintf("grid grid-cols-%d %s", cols, class) }>
        { children... }
    </div>
}
`
	return renderer.OutputFile{
		Path:    "components/layout_helpers.templ",
		Content: []byte(content),
	}
}

func generateButtonTempl() renderer.OutputFile {
	content := `// button.templ
// Generated by Sigil — do not edit manually
package components

// ButtonProps defines the props for the Button component.
type ButtonProps struct {
    Label    string
    Variant  string // primary, secondary, destructive, outline, ghost
    Icon     string
    Disabled bool
    HxGet    string
    HxPost   string
    HxTarget string
    HxSwap   string
    HxConfirm string
}

templ Button(props ButtonProps) {
    <button
        class={ "sigil-btn sigil-btn-" + props.Variant }
        disabled?={ props.Disabled }
        if props.HxGet != "" {
            hx-get={ props.HxGet }
        }
        if props.HxPost != "" {
            hx-post={ props.HxPost }
        }
        if props.HxTarget != "" {
            hx-target={ props.HxTarget }
        }
        if props.HxSwap != "" {
            hx-swap={ props.HxSwap }
        }
        if props.HxConfirm != "" {
            hx-confirm={ props.HxConfirm }
        }
    >
        if props.Icon != "" {
            <span class={ "icon icon-" + props.Icon }></span>
        }
        <span>{ props.Label }</span>
    </button>
}
`
	return renderer.OutputFile{
		Path:    "components/button.templ",
		Content: []byte(content),
	}
}

