func TestRenderHTMXAttrs(t *testing.T) {
	tests := []struct {
		name     string
		actions  map[string]config.Action
		contains []string
	}{
		{
			name: "navigate with URL",
			actions: map[string]config.Action{
				"click": {Type: "navigate", URL: "/dashboard"},
			},
			contains: []string{`hx-get="/dashboard"`, `hx-push-url="true"`},
		},
		{
			name: "navigate with page",
			actions: map[string]config.Action{
				"click": {Type: "navigate", Page: "home"},
			},
			contains: []string{`hx-get="/ui/pages/home"`},
		},
		{
			name: "http POST",
			actions: map[string]config.Action{
				"click": {Type: "http", URL: "/api/sprints", Method: "POST"},
			},
			contains: []string{`hx-post="/api/sprints"`},
		},
		{
			name: "http DELETE",
			actions: map[string]config.Action{
				"click": {Type: "http", URL: "/api/sprints/1", Method: "DELETE"},
			},
			contains: []string{`hx-delete="/api/sprints/1"`},
		},
		{
			name: "confirm with nested",
			actions: map[string]config.Action{
				"click": {
					Type:    "confirm",
					Message: "Are you sure?",
					OnConfirm: &config.Action{
						Type: "http", URL: "/api/delete", Method: "DELETE",
					},
				},
			},
			contains: []string{`hx-confirm="Are you sure?"`, `hx-delete="/api/delete"`},
		},
		{
			name:     "empty actions",
			actions:  map[string]config.Action{},
			contains: []string{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := renderHTMXAttrs(tt.actions)
			for _, expected := range tt.contains {
				if !strings.Contains(result, expected) {
					t.Errorf("expected %q in result %q", expected, result)
				}
			}
		})
	}
}

