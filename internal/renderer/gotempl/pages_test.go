func TestRenderSimplePage(t *testing.T) {
	ctx := &renderer.RenderContext{
		Page: &config.Page{
			ID:      "test-page",
			Title:   "Test Page",
			Overlay: "page",
			Layout: config.Component{
				ID:   "root",
				Type: "rows",
				Props: map[string]interface{}{
					"gap":     "4",
					"padding": "6",
				},
				Children: []config.Component{
					{
						ID:   "title",
						Type: "heading",
						Props: map[string]interface{}{
							"level": "2",
							"text":  "Hello World",
						},
					},
				},
			},
		},
	}

	files, err := renderPage(ctx)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("expected 1 file, got %d", len(files))
	}

	file := files[0]
	if file.Path != "pages/test_page.templ" {
		t.Errorf("expected path 'pages/test_page.templ', got %q", file.Path)
	}

	content := string(file.Content)
	if !strings.Contains(content, "templ TestPage()") {
		t.Error("expected templ function declaration")
	}
	if !strings.Contains(content, "Generated by Sigil") {
		t.Error("expected generated header comment")
	}
	if !strings.Contains(content, "flex flex-col") {
		t.Error("expected rows rendered as flex-col")
	}
	if !strings.Contains(content, "Hello World") {
		t.Error("expected heading text")
	}
}

